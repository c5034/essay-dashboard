-- 1. 내 기본 지역 저장용 표(saved_regions) 생성
create table if not exists saved_regions (
  id bigint generated by default as identity primary key,
  sido text not null,
  sigungu text not null,
  created_at timestamptz default now() not null
);

-- 2. 표 보안 규칙(RLS) 활성화
alter table saved_regions enable row level security;

-- 3. 기존 정책이 있을 경우 삭제 후 재등록 (중복 에러 방지)
drop policy if exists "누구나 지역 저장 가능" on saved_regions;
drop policy if exists "누구나 저장된 지역 조회 가능" on saved_regions;

-- 4. 누구나 줄을 넣는(저장하는) 규칙
create policy "누구나 지역 저장 가능"
  on saved_regions
  for insert
  to anon
  with check (true);

-- 5. 누구나 줄을 보는(조회하는) 규칙
create policy "누구나 저장된 지역 조회 가능"
  on saved_regions
  for select
  to anon
  using (true);
